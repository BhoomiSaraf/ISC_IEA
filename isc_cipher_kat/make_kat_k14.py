"""Generate known-answer vectors for the new VERSION=2 / k14_scaled_modulo_v1 extraction profile
(Phase 3A). Run on Windows (E1) from the project root, exactly like make_kat.py:

    python isc_cipher_kat/make_kat_k14.py

This does NOT touch, regenerate, or overwrite any existing vector file (trig_kat.txt.gz,
traj_kat.json, stream_kat.json, cipher_kat.json, PROVENANCE.json): the ISC recurrence and its
trigonometric evaluation are completely unchanged by the new extraction profile, so the existing
KAT-1 (trig) and KAT-2 (trajectory) vectors already cover the mathematics this profile depends on.
Only the byte-extraction step itself is new, so only two new, separate vector files are produced:

  vectors/stream_kat_k14.json   same methodology as KAT 2b in make_kat.py (independent C oracle,
                                 fdlibm 5.3, burn_in=1024, 8 output steps), but the stream bytes are
                                 computed with frac_byte (k=14 scaled-floor-modulo) instead of
                                 m_byte -- independent of the Python cipher implementation.
  vectors/cipher_kat_k14.json   same methodology as KAT 3 in make_kat.py: self-generated by R1
                                 (pure-Python reference backend) for VERSION=2/extraction=2
                                 ciphertexts; NOT independent (cross-checked against V1/numpy by
                                 gate_r_k14.py instead).

Refuses to overwrite existing vectors (including its own outputs, on a second run).
"""

import gzip
import hashlib
import json
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "isc_cipher_kat"))

from make_kat import K_TEST, N_TEST, d2h, h2d, run_oracle, state_hash, traj_from_oracle  # noqa: E402
from isc_cipher import kdf  # noqa: E402
from isc_cipher._testing import encrypt_bytes_with_nonce_TEST_ONLY, materials_TEST_ONLY  # noqa: E402
from isc_cipher.generator import EXTRACTION_K14_SCALED_MODULO_V1 as E2  # noqa: E402
from isc_cipher.state_map import seed_to_state  # noqa: E402
from isc_seq.extract import frac_byte  # noqa: E402

HERE = os.path.join(ROOT, "isc_cipher_kat")
VEC = os.path.join(HERE, "vectors")


def frac_byte_hex(xh):
    """frac_byte of the float64 value whose big-endian hex representation is xh."""
    return int(frac_byte(h2d(xh)))


def main():
    os.makedirs(VEC, exist_ok=True)
    targets = ["stream_kat_k14.json", "cipher_kat_k14.json"]
    for t in targets:
        if os.path.exists(os.path.join(VEC, t)):
            sys.exit(f"refusing to overwrite {t}")

    # --- stream KAT (k14), independent C oracle for the trajectory, Python frac_byte for bytes ---
    der = kdf.Derivation(K_TEST, N_TEST, kdf.context(1, 1, 64, 64, 3, extraction=E2))
    seeds = der.seeds()
    stream_kat = {"key_hex": K_TEST.hex(), "nonce_hex": N_TEST.hex(), "shape": [64, 64, 3], "profile": 1,
                  "extraction": E2, "extraction_name": "k14_scaled_modulo_v1",
                  "ctx_hex": kdf.context(1, 1, 64, 64, 3, extraction=E2).hex(),
                  "burn_in": 1024, "output_steps": 8, "streams": {}}
    for g in kdf.STREAMS:
        lane_ics = [seed_to_state(s) for s in seeds[g]]
        res = traj_from_oracle(lane_ics, 1024, 8)
        by = bytearray()
        for j in range(8):
            for lane in res:
                xh, yh = lane["O"][j]
                by += bytes([frac_byte_hex(xh), frac_byte_hex(yh)])
        stream_kat["streams"][g] = {
            "seeds_hex": [s.hex() for s in seeds[g]],
            "initial_states": [[d2h(x), d2h(y)] for x, y in lane_ics],
            "after_burn_in": [list(lane["B"][-1]) for lane in res],
            "first_1024_bytes_hex": by.hex(),
            "states_after_8_steps": [list(lane["O"][-1]) for lane in res],
        }
    json.dump(stream_kat, open(os.path.join(VEC, "stream_kat_k14.json"), "x"), indent=1)
    print("stream KAT (k14) done")

    # --- cipher KAT (k14), self-generated by R1 (pure-Python reference backend), VERSION=2 ---
    cases = []
    for shape in [(1, 1, 1), (1, 7, 1), (7, 1, 1), (4, 6, 3), (16, 16, 1), (64, 64, 3)]:
        h, w, c = shape
        n = h * w * c
        data = bytes((i * 37 + 11) % 256 for i in range(n))
        mats = materials_TEST_ONLY(K_TEST, N_TEST, h, w, c, backend="reference", extraction=E2)
        z = encrypt_bytes_with_nonce_TEST_ONLY(K_TEST, data, h, w, c, N_TEST, backend="reference", extraction=E2)
        assert z[4] == 2 and z[36] == E2          # VERSION=2, EXTRACTION=k14
        pi_bytes = b"".join(i.to_bytes(4, "big") for i in mats["pi"])
        cases.append({
            "shape": [h, w, c], "plaintext_rule": "p_i = (37*i + 11) mod 256",
            "sbox_hex": bytes(mats["S"]).hex(), "iv_f": mats["iv_f"], "iv_b": mats["iv_b"],
            "pi": mats["pi"] if n <= 256 else None, "pi_sha256": hashlib.sha256(pi_bytes).hexdigest(),
            "a_prefix_hex": mats["a"][:1024].hex(), "b_prefix_hex": mats["b"][:1024].hex(),
            "kcv_hex": z[28:36].hex(), "body_sha256": hashlib.sha256(z[37:37 + n]).hexdigest(),
            "ciphertext_hex": z.hex() if n <= 300 else None, "ciphertext_sha256": hashlib.sha256(z).hexdigest(),
            "steps": {g: mats["streams"][g].steps for g in kdf.STREAMS},
        })
        print("cipher KAT (k14)", shape)
    json.dump({"generated_by": "R1 (pure-Python reference) on E1; NOT independent; VERSION=2, extraction=2 "
               "(k14_scaled_modulo_v1); cross-check against the numpy backend is gate_r_k14.py's job",
               "key_hex": K_TEST.hex(), "nonce_hex": N_TEST.hex(), "extraction": E2,
               "header_len": 37, "cases": cases}, open(os.path.join(VEC, "cipher_kat_k14.json"), "x"), indent=1)
    print("done")


if __name__ == "__main__":
    main()
