"""Generate the ISC-IMG v1 known-answer vectors (Gate R).  Run on Windows (E1) from the project root:

    python isc_cipher_kat/make_kat.py

Independent expected values (C oracle linked against the unmodified fdlibm 5.3 sources, built and run in
WSL Ubuntu by isc_cipher_kat/oracle/build_oracle.sh):
  vectors/trig_kat.txt.gz      sin/cos bit patterns for every argument class (KAT 1)
  vectors/traj_kat.json        10 ISC trajectories x 100000 steps: SHA-256 of all states + checkpoints (KAT 2)
  vectors/stream_kat.json      first 1024 bytes and 8-step states of all 4 streams for (K_test, N_test, 64x64x3)
Self-generated by R1 (pure-Python reference) and therefore NOT independent; checked across implementations
(V1 on E1, R1 on E2):
  vectors/cipher_kat.json      S-box, permutation, stream prefixes, KCV, body and ciphertext hashes (KAT 3)
Also writes isc_cipher/_selftest_vectors.py (subset of oracle values) and vectors/PROVENANCE.json.
Refuses to overwrite existing vectors.
"""

import gzip
import hashlib
import json
import os
import platform
import struct
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from isc_cipher import kdf  # noqa: E402
from isc_cipher._testing import encrypt_bytes_with_nonce_TEST_ONLY, materials_TEST_ONLY  # noqa: E402
from isc_cipher.state_map import seed_to_state  # noqa: E402

HERE = os.path.join(ROOT, "isc_cipher_kat")
VEC = os.path.join(HERE, "vectors")
ORACLE = os.path.join(HERE, "oracle", "build", "oracle")
DISTRO = "Ubuntu-24.04"
K_TEST = bytes(range(32))           # PUBLIC test key - never use for real data
N_TEST = bytes(range(16))           # PUBLIC test nonce


def wsl_path(p):
    p = os.path.abspath(p)
    return "/mnt/" + p[0].lower() + p[2:].replace("\\", "/")


def run_oracle(mode, text):
    proc = subprocess.run(["wsl", "-d", DISTRO, "--", wsl_path(ORACLE), mode], input=text.encode(),
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)
    return proc.stdout.decode()


def d2h(v):
    return struct.pack(">d", v).hex()


def h2d(h):
    return struct.unpack(">d", bytes.fromhex(h))[0]


def from_words(hw, lw):
    return struct.unpack(">d", struct.pack(">II", hw & 0xFFFFFFFF, lw & 0xFFFFFFFF))[0]


def ulp_neighbours(v, k):
    u = struct.unpack(">Q", struct.pack(">d", v))[0]
    return [struct.unpack(">d", struct.pack(">Q", u + d))[0] for d in range(-k, k + 1)]


def trig_arguments():
    import numpy as np
    args = []
    # fdlibm branch thresholds (high words) with assorted low words, neighbours and both signs
    for hw in (0x3FE921FB, 0x4002D97C, 0x3FF921FB, 0x3FE90000, 0x3FD33333, 0x3E400000, 0x413921FB):
        for dh in (-1, 0, 1):
            for lw in (0, 1, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF):
                v = from_words(hw + dh, lw)
                if abs(v) < 24:
                    args += [v, -v]
    # neighbourhoods of k*pi/2 (k = 1..15): exercise the 2nd/3rd reduction iterations and npio2_hw
    for k in range(1, 16):
        base = k * (3.141592653589793 / 2)
        for v in ulp_neighbours(base, 64):
            args += [v, -v]
    # constants used in tests and grid points
    args += [0.0, -0.0, 0.1, -5.6, -1.6, 22.73, -2.73, 12.73, -12.73, 1e-300, 5e-324, 2.0 ** -28, -(2.0 ** -28)]
    rng = np.random.Generator(np.random.PCG64(20261026))
    args += list(rng.uniform(-24.0, 24.0, 50000))
    mag = 2.0 ** rng.uniform(-30, 0, 20000)
    args += list(mag * np.where(rng.random(20000) < 0.5, -1.0, 1.0))
    return [float(a) for a in args]


TRAJ_ICS = [(0.1, 0.1), (-1.0, -1.0), (1 - 2 ** -52, 1 - 2 ** -52), (0.0, 0.0), (-1.0, 1 - 2 ** -52),
            (0.5, -0.5), (-2 ** -52, 2 ** -52)]
TRAJ_STEPS = 100000
CHECKPOINTS = (1, 10, 100, 1000, 10000, 100000)


def traj_from_oracle(ics, burn, outs):
    text = "".join(f"{d2h(x)} {d2h(y)} {burn} {outs}\n" for x, y in ics)
    out = run_oracle("traj", text)
    res, cur = [], None
    for line in out.splitlines():
        p = line.split()
        if p[0] == "S":
            cur = {"x0": p[1], "y0": p[2], "burn": int(p[3]), "outs": int(p[4]), "B": [], "O": []}
            res.append(cur)
        else:
            cur[p[0]].append((p[2], p[3]))
    return res


def state_hash(states):
    h = hashlib.sha256()
    for xh, yh in states:
        h.update(bytes.fromhex(xh) + bytes.fromhex(yh))
    return h.hexdigest()


def m_byte_hex(xh):
    return bytes.fromhex(xh)[6]


def main():
    os.makedirs(VEC, exist_ok=True)
    targets = ["trig_kat.txt.gz", "traj_kat.json", "stream_kat.json", "cipher_kat.json", "PROVENANCE.json"]
    for t in targets:
        if os.path.exists(os.path.join(VEC, t)):
            sys.exit(f"refusing to overwrite {t}")
    # --- KAT 1: sin/cos -----------------------------------------------------------------------
    args = trig_arguments()
    out = run_oracle("trig", "".join(d2h(a) + "\n" for a in args))
    lines = out.splitlines()
    assert len(lines) == len(args)
    with gzip.open(os.path.join(VEC, "trig_kat.txt.gz"), "wt", encoding="ascii") as f:
        f.write("# arg_hex sin_hex cos_hex  (C oracle, fdlibm 5.3)\n")
        f.write("\n".join(lines) + "\n")
    print("trig vectors:", len(lines))
    # --- KAT 2: trajectories -------------------------------------------------------------------
    der = kdf.Derivation(K_TEST, N_TEST, kdf.context(1, 1, 64, 64, 3))
    seeds = der.seeds()
    ics = TRAJ_ICS + [seed_to_state(seeds["fwd"][0]), seed_to_state(seeds["perm"][63]), seed_to_state(seeds["sbox"][7])]
    trajs = traj_from_oracle(ics, 0, TRAJ_STEPS)
    traj_kat = []
    for (x0, y0), t in zip(ics, trajs):
        assert t["x0"] == d2h(x0) and len(t["O"]) == TRAJ_STEPS
        traj_kat.append({"x0": d2h(x0), "y0": d2h(y0), "steps": TRAJ_STEPS, "sha256_all_states": state_hash(t["O"]),
                         "checkpoints": {str(c): list(t["O"][c - 1]) for c in CHECKPOINTS}})
    json.dump({"description": "ISC trajectories, profile 1, no burn-in; state i is after i steps; "
               "hash = SHA-256 over BE64(x)||BE64(y) for i = 1..steps (C oracle)", "trajectories": traj_kat},
              open(os.path.join(VEC, "traj_kat.json"), "x"), indent=1)
    print("trajectories:", len(traj_kat))
    # --- KAT 2b: streams for (K_test, N_test, 64x64x3), C oracle -------------------------------
    stream_kat = {"key_hex": K_TEST.hex(), "nonce_hex": N_TEST.hex(), "shape": [64, 64, 3], "profile": 1,
                  "burn_in": 1024, "output_steps": 8, "streams": {}}
    for g in kdf.STREAMS:
        lane_ics = [seed_to_state(s) for s in seeds[g]]
        res = traj_from_oracle(lane_ics, 1024, 8)
        by = bytearray()
        for j in range(8):
            for lane in res:
                xh, yh = lane["O"][j]
                by += bytes([m_byte_hex(xh), m_byte_hex(yh)])
        stream_kat["streams"][g] = {
            "seeds_hex": [s.hex() for s in seeds[g]],
            "initial_states": [[d2h(x), d2h(y)] for x, y in lane_ics],
            "after_burn_in": [list(lane["B"][-1]) for lane in res],
            "first_1024_bytes_hex": by.hex(),
            "states_after_8_steps": [list(lane["O"][-1]) for lane in res],
        }
    json.dump(stream_kat, open(os.path.join(VEC, "stream_kat.json"), "x"), indent=1)
    print("stream KAT done")
    # --- self-test subset (oracle values) --------------------------------------------------------
    sub = [l.split() for l in lines[:120:3]]
    t0 = traj_from_oracle([(0.1, 0.1)], 0, 16)[0]
    with open(os.path.join(ROOT, "isc_cipher", "_selftest_vectors.py"), "x", encoding="ascii") as f:
        f.write('"""Generated by isc_cipher_kat/make_kat.py from the fdlibm C oracle. Do not edit."""\n\n')
        f.write("TRIG = [\n" + "".join(f"    ({a!r}, {s!r}, {c!r}),\n" for a, s, c in sub) + "]\n\n")
        f.write(f"TRAJ = {{'x0': {d2h(0.1)!r}, 'y0': {d2h(0.1)!r}, 'steps': 16, "
                f"'x': {t0['O'][-1][0]!r}, 'y': {t0['O'][-1][1]!r}}}\n")
    # --- KAT 3: full cipher (R1, self-generated) -----------------------------------------------
    cases = []
    for shape in [(1, 1, 1), (1, 7, 1), (7, 1, 1), (4, 6, 3), (16, 16, 1), (64, 64, 3)]:
        h, w, c = shape
        n = h * w * c
        data = bytes((i * 37 + 11) % 256 for i in range(n))
        mats = materials_TEST_ONLY(K_TEST, N_TEST, h, w, c, backend="reference")
        z = encrypt_bytes_with_nonce_TEST_ONLY(K_TEST, data, h, w, c, N_TEST, backend="reference")
        pi_bytes = b"".join(i.to_bytes(4, "big") for i in mats["pi"])
        cases.append({
            "shape": [h, w, c], "plaintext_rule": "p_i = (37*i + 11) mod 256",
            "sbox_hex": bytes(mats["S"]).hex(), "iv_f": mats["iv_f"], "iv_b": mats["iv_b"],
            "pi": mats["pi"] if n <= 256 else None, "pi_sha256": hashlib.sha256(pi_bytes).hexdigest(),
            "a_prefix_hex": mats["a"][:1024].hex(), "b_prefix_hex": mats["b"][:1024].hex(),
            "kcv_hex": z[28:36].hex(), "body_sha256": hashlib.sha256(z[36:36 + n]).hexdigest(),
            "ciphertext_hex": z.hex() if n <= 300 else None, "ciphertext_sha256": hashlib.sha256(z).hexdigest(),
            "steps": {g: mats["streams"][g].steps for g in kdf.STREAMS},
        })
        print("cipher KAT", shape)
    json.dump({"generated_by": "R1 (pure-Python reference) on E1; NOT independent", "key_hex": K_TEST.hex(),
               "nonce_hex": N_TEST.hex(), "cases": cases}, open(os.path.join(VEC, "cipher_kat.json"), "x"), indent=1)
    # --- provenance --------------------------------------------------------------------------------
    info = open(os.path.join(HERE, "oracle", "build", "BUILD_INFO.txt"), encoding="utf-8").read()
    prov = {
        "generated_utc": __import__("datetime").datetime.now(__import__("datetime").timezone.utc).isoformat(timespec="seconds"),
        "host": platform.platform(), "python": sys.version.split()[0],
        "oracle_build": info, "fdlibm_sha256": open(os.path.join(ROOT, "third_party", "fdlibm", "netlib_5.3", "SHA256SUMS.txt")).read(),
        "make_kat_sha256": hashlib.sha256(open(__file__, "rb").read()).hexdigest(),
        "independent": ["trig_kat.txt.gz", "traj_kat.json", "stream_kat.json (seeds derived by isc_cipher.kdf, which is "
                        "checked separately against RFC 5869 vectors and the cryptography library)"],
        "self_generated": ["cipher_kat.json (R1)"],
        "public_test_key_hex": K_TEST.hex(), "public_test_nonce_hex": N_TEST.hex(),
    }
    json.dump(prov, open(os.path.join(VEC, "PROVENANCE.json"), "x"), indent=1)
    print("done")


if __name__ == "__main__":
    main()
